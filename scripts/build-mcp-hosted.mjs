#!/usr/bin/env node
/* Generates api/mcp-remote/read-tools.gen.js, the committed bundle the hosted MCP endpoint runs:
 * mcp/src/hosted.js with V1's read tools and the frontend/src/lib modules they compute with.
 *
 *   node scripts/build-mcp-hosted.mjs           # write
 *   node scripts/build-mcp-hosted.mjs --check   # fail if stale (CI, frontend job)
 *
 * The same arrangement as build-coach-assets.mjs, for the same reason: the API image is built from
 * api/ alone and carries nothing of frontend/, yet the numbers an assistant is told (1RMs, volume,
 * the week plan) have to be the ones the app shows. Bundling the app's own code is how they stay
 * the same; a hand-written copy would drift. Two substitutions:
 *
 *   - mcp/src/state.js becomes mcp/src/hosted-state.js: one process serves every connected
 *     profile, so the tools read whichever profile the current call is for;
 *   - zod stays external: the API resolves it from its own node_modules (the version the MCP SDK
 *     there needs), rather than carrying a second copy inside this file.
 *
 * Needs frontend's dev dependencies (rolldown comes with vite): `npm --prefix frontend ci`. */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'api', 'mcp-remote', 'read-tools.gen.js');
const check = process.argv.includes('--check');

const req = createRequire(join(root, 'frontend', 'package.json'));
const { rolldown } = await import(pathToFileURL(req.resolve('rolldown')).href);

const stateFile = join(root, 'mcp', 'src', 'state.js');
const hostedState = join(root, 'mcp', 'src', 'hosted-state.js');

const bundle = await rolldown({
  input: join(root, 'mcp', 'src', 'hosted.js'),
  external: ['zod'],
  platform: 'node',
  treeshake: true,
  plugins: [{
    name: 'hosted-state',
    resolveId(source, importer) {
      if (!importer || !source.startsWith('.')) return null;
      return join(dirname(importer), source) === stateFile ? hostedState : null;
    }
  }]
});
const { output } = await bundle.generate({ format: 'esm', minify: false, comments: { legal: false, annotation: false, jsdoc: false } });
await bundle.close();
if (output.length !== 1) throw new Error(`expected one chunk, got ${output.length}`);

// Paths in the bundle's region comments are made relative, so the file is the same on every machine.
const code = output[0].code.split(root + '/').join('');
const text = `/* GENERATED by scripts/build-mcp-hosted.mjs from mcp/src/hosted.js — do not edit.\n   SPDX-License-Identifier: AGPL-3.0-or-later */\n${code}`;

if (check) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch { /* missing is stale */ }
  if (cur !== text) {
    console.error('api/mcp-remote/read-tools.gen.js is stale: run node scripts/build-mcp-hosted.mjs');
    process.exit(1);
  }
  console.log('read-tools.gen.js is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${(text.length / 1024).toFixed(0)} KB)`);
}
